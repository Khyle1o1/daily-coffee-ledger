/**
 * Regenerates src/utils/defaultMapping.ts from public/Validation.xlsx (MENU 8172026).
 * Run: node scripts/generate-default-mapping.mjs
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import XLSX from "xlsx";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const xlsxPath = path.join(root, "public", "Validation.xlsx");
const outPath = path.join(root, "src", "utils", "defaultMapping.ts");

function pick(row, keys) {
  const wanted = new Set(keys.map((k) => k.trim().toLowerCase()));
  for (const key of Object.keys(row)) {
    if (!wanted.has(key.trim().toLowerCase())) continue;
    const value = row[key];
    if (value == null) continue;
    const text = String(value).trim();
    if (text) return text;
  }
  return "";
}

function canonicalizeMappedName(raw) {
  return raw.trim().toUpperCase().replace(/^ADD ONS$/, "ADD-ONS");
}

function canonicalizeSourceCategory(raw) {
  const stripped = raw.replace(/^\d{1,3}\s*[.)-]?\s+/i, "").trim();
  const aliases = {
    "ADD ONS": "ADD-ONS",
    "DEL - ADD ONS": "DEL-ADD-ONS",
    "DEL ADD ONS": "DEL-ADD-ONS",
  };
  return aliases[stripped.toUpperCase()] ?? stripped;
}

function esc(s) {
  return String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

const wb = XLSX.readFile(xlsxPath);
const sheet = wb.Sheets["MENU 8172026"];
if (!sheet) {
  console.error("Missing MENU 8172026 sheet");
  process.exit(1);
}

const records = XLSX.utils.sheet_to_json(sheet, { defval: "" });
const rows = records
  .map((r) => ({
    mappedName: canonicalizeMappedName(pick(r, ["validation", "mapped name", "mappedname"])),
    category: canonicalizeSourceCategory(pick(r, ["category"])),
    item: pick(r, ["item"]),
    option: pick(r, ["option"]),
  }))
  .filter((r) => r.mappedName && r.category && r.item);

const grouped = [];
let current;
for (const row of rows) {
  const groupKey = `${row.mappedName}|||${row.category}`;
  if (!current || current.key !== groupKey) {
    current = { key: groupKey, mappedName: row.mappedName, category: row.category, rows: [] };
    grouped.push(current);
  }
  current.rows.push(row);
}

const body = grouped
  .map((g) => {
    const header = `  // ── ${g.mappedName} / ${g.category} ──`;
    const lines = g.rows.map(
      (r) => `  ["${esc(r.mappedName)}","${esc(r.category)}","${esc(r.item)}","${esc(r.option)}"],`,
    );
    return [header, ...lines].join("\n");
  })
  .join("\n\n");

const source = `import type { MappingEntry } from "./types";
import { toMappingEntries, normalizeOption } from "./validationMapping";

/**
 * Raw validation table extracted from public/Validation.xlsx (MENU 8172026).
 * Format: [mappedName, category, item, option]
 *
 * Add-on bucket rows are expanded at compile time (outputItem + flattened aliases).
 * Regenerated by: node scripts/generate-default-mapping.mjs
 */
const RAW: [string, string, string, string][] = [
${body}
];

/** Compiled mapping table with pre-normalized lookup keys. */
export const DEFAULT_MAPPING: MappingEntry[] = toMappingEntries(
  RAW.map(([mappedName, category, item, option]) => ({ mappedName, category, item, option })),
);

/** Exported for use in mapRow helpers. */
export { normalizeOption };
`;

fs.writeFileSync(outPath, source);
console.log(`Wrote ${rows.length} RAW rows to ${path.relative(root, outPath)}`);
